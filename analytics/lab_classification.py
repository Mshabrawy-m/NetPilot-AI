"""Label-gated fault classification for the AI Lab (Phase 5).

Supervised fault classification is only run when the source really carries
class labels. If it does not, this module returns an explicit refusal instead
of a fabricated accuracy number - there is no way to invent a fault label for
live telemetry, and pretending otherwise would produce the single most
misleading artefact an AIOps project can ship.

Protocol enforced here:

* the split is chosen deliberately and recorded: ``chronological`` (train in
  the past, test in the future - the only honest protocol for time-series
  operations data) or ``stratified`` (random, balanced classes - valid only for
  pooled non-temporal records, and it leaks future context into training, so
  the result says so);
* fill/scaling parameters are learned on TRAIN rows only
  (``analytics.lab_dataset.TrainPreprocessor``) and only then applied to test
  rows, so no test statistic can influence the fitted transform;
* class imbalance is handled explicitly (``class_weight``) and reported with
  imbalance-aware metrics (balanced accuracy, macro-F1, per-class support),
  because plain accuracy on a 99/1 split is meaningless;
* a class that never appears in TRAIN cannot be predicted - the affected model
  is reported as skipped with that reason rather than silently dropped from the
  table;
* results carry the label provenance (simulated ground truth vs. operator
  assertion), so a 0.98 F1 on synthetic labels is never read as field accuracy;
* a flawless separation is reported *with a warning* that labels generated by
  the same events that drive the features are separable by construction.
"""
from __future__ import annotations

import dataclasses
import math
import warnings

import pandas as pd

from analytics.lab_dataset import TrainPreprocessor
from config import get_settings

#: Model registry. All entries are scikit-learn estimators already required by
#: the project - no deep-learning stack is introduced for this feature.
CLASSIFIERS = {
    "logistic_regression": "multinomial logistic regression (L2, class_weight=balanced)",
    "random_forest": "random forest (class_weight=balanced_subsample)",
    "gradient_boosting": "sklearn HistGradientBoosting (no class weighting)",
}

#: Minimum rows per class, below which a class cannot be learned defensibly.
MIN_ROWS_PER_CLASS = 4

SPLIT_CHRONOLOGICAL = "chronological"
SPLIT_STRATIFIED = "stratified"

SPLIT_NOTES = {
    SPLIT_CHRONOLOGICAL: (
        "train precedes test in time: no future information is available to "
        "the fit, which is the protocol an operational forecast must satisfy"),
    SPLIT_STRATIFIED: (
        "randomised, class-balanced split: rows from the future sit in the "
        "training set, so scores are optimistic for time-ordered telemetry and "
        "only defensible for pooled non-temporal records"),
}


@dataclasses.dataclass
class ClassificationRefusal:
    """A refusal is a first-class result: reason plus what would be needed."""

    reason: str
    detail: str
    needed: dict

    def as_dict(self) -> dict:
        return {"status": "refused", "reason": self.reason,
                "detail": self.detail, "needed": self.needed}


def evaluate_classification(
    features: pd.DataFrame,
    timestamps: pd.Series,
    labels: pd.Series,
    *,
    models: tuple[str, ...] = ("logistic_regression", "random_forest"),
    test_frac: float = 0.25,
    split_mode: str = SPLIT_CHRONOLOGICAL,
    random_seed: int = 42,
    label_provenance: str = "",
    max_features: int = 24,
) -> dict:
    """Train/compare classifiers on one aligned feature matrix.

    Returns ``{"status": "ok"|"refused", ...}``. Nothing raises for thin or
    unlabelled data: a refusal with the concrete precondition is the result.
    """
    refusal = _validate(features, timestamps, labels, split_mode=split_mode)
    if refusal is not None:
        return refusal.as_dict()

    settings = get_settings()
    labels = labels.reset_index(drop=True)
    features = features.reset_index(drop=True)
    timestamps = pd.Series(timestamps).reset_index(drop=True)
    if features.shape[1] > max_features:
        # Bounding the width keeps the feature list inspectable and stops a
        # 400-column export from turning into an unreviewable model.
        features = features.iloc[:, :max_features]

    classes = sorted({str(v) for v in labels.tolist()})
    counts = labels.astype(str).value_counts()

    train_idx, test_idx = _make_split(labels, test_frac=test_frac,
                                      split_mode=split_mode)
    if len(train_idx) < settings.min_points_detection:
        return ClassificationRefusal(
            "insufficient_train_rows",
            f"the split leaves {len(train_idx)} training rows, below the "
            f"detection floor of {settings.min_points_detection}.",
            {"min_train_rows": settings.min_points_detection,
             "available_rows": int(len(labels))}).as_dict()

    train_features = features.iloc[train_idx]
    test_features = features.iloc[test_idx]
    train_labels = labels.iloc[train_idx].astype(str)
    test_labels = labels.iloc[test_idx].astype(str)

    # ---- train-only preprocessing (fit BEFORE any test statistic exists) --
    pre = TrainPreprocessor.fit(train_features)
    x_train = pre.transform(train_features)
    x_test = pre.transform(test_features)

    missing_in_train = [c for c in classes if c not in set(train_labels)]
    missing_in_test = [c for c in classes if c not in set(test_labels)]

    rows: list[dict] = []
    artifacts: dict = {"confusion_matrices": {}, "feature_importance": {},
                       "classes": classes}
    from sklearn.metrics import (accuracy_score, balanced_accuracy_score,
                                 confusion_matrix, f1_score,
                                 precision_recall_fscore_support)

    for name in models:
        if name not in CLASSIFIERS:
            rows.append({"model": name, "status": "unknown_model"})
            continue
        if missing_in_train:
            rows.append({"model": name, "status": "skipped",
                         "reason": (f"class(es) {missing_in_train} never appear "
                                    "in the training split, so the model cannot "
                                    "learn them under this split protocol")})
            continue
        try:
            estimator = _build(name, random_seed)
            # scipy used by this environment ignores an option scikit-learn
            # still passes to its L-BFGS solver and warns on every fit. The
            # optimisation is unaffected, so that one benign message is
            # filtered; convergence warnings are not, and still surface as
            # ordinary Python warnings for the caller to decide about.
            with warnings.catch_warnings():
                warnings.filterwarnings("ignore",
                                        message="Unknown solver options.*")
                estimator.fit(x_train, train_labels)
            predicted = [str(p) for p in estimator.predict(x_test)]
        except Exception as exc:
            rows.append({"model": name, "status": "error",
                         "reason": f"{type(exc).__name__}: {str(exc)[:180]}"})
            continue
        ordered_test = classes
        # scikit-learn warns when the held-out rows contain a single class. That
        # condition is already detected and reported here as "classes absent from
        # the test split", so the duplicate library warning is silenced instead
        # of surfacing to the user as an unexplained error line.
        with warnings.catch_warnings():
            warnings.filterwarnings(
                "ignore", message="A single label was found.*")
            matrix = confusion_matrix(test_labels, predicted,
                                      labels=ordered_test)
            precision, recall, f1, support = precision_recall_fscore_support(
                test_labels, predicted, labels=ordered_test, zero_division=0)
            scores = {
                "accuracy": float(accuracy_score(test_labels, predicted)),
                "balanced_accuracy": float(
                    balanced_accuracy_score(test_labels, predicted)),
                "macro_f1": float(f1_score(test_labels, predicted,
                                           labels=ordered_test,
                                           average="macro", zero_division=0)),
                "weighted_f1": float(f1_score(test_labels, predicted,
                                              labels=ordered_test,
                                              average="weighted",
                                              zero_division=0)),
            }
        rows.append({
            "model": name, "status": "ok",
            "description": CLASSIFIERS[name],
            "n_train": len(train_idx), "n_test": len(test_idx),
            "accuracy": scores["accuracy"],
            "balanced_accuracy": scores["balanced_accuracy"],
            "macro_f1": scores["macro_f1"],
            "weighted_f1": scores["weighted_f1"],
            "per_class": [
                {"class": c, "support": int(support[i]),
                 "precision": _num(precision[i]), "recall": _num(recall[i]),
                 "f1": _num(f1[i])}
                for i, c in enumerate(ordered_test)],
            "majority_baseline": float(max(counts.tolist()) / counts.sum()),
        })
        artifacts["confusion_matrices"][name] = {
            "classes": ordered_test,
            "matrix": [[int(v) for v in row] for row in matrix],
            "orientation": "rows = true class, columns = predicted class",
        }
        artifacts["feature_importance"][name] = _importances(
            estimator, list(x_train.columns))

    return {
        "status": "ok",
        "metrics": {
            "n_rows": int(len(labels)), "n_features": int(x_train.shape[1]),
            "n_train": len(train_idx), "n_test": len(test_idx),
            "classes": classes,
            "class_counts": {str(k): int(v) for k, v in counts.items()},
            "imbalance_ratio": round(float(counts.max())
                                     / max(1, int(counts.min())), 2),
            "best_model": _best(rows),
            "best_criterion": "balanced accuracy (macro-F1 as tie-break)",
        },
        "table": rows,
        "artifacts": artifacts,
        "warnings": _warnings(missing_in_train, missing_in_test, split_mode,
                              classes, counts) + _perfect_split_notes(rows),
        "config": {
            "models": list(models), "test_frac": test_frac,
            "split_mode": split_mode, "split_note": SPLIT_NOTES[split_mode],
            "random_seed": random_seed,
            "preprocessing": pre.config(),
            "imbalance_handling": ("class_weight=balanced / "
                                   "balanced_subsample where the estimator "
                                   "supports it; gradient boosting has no "
                                   "class weighting, so read its accuracy "
                                   "against the majority baseline"),
            "label_provenance": label_provenance or "not stated",
            "feature_columns": list(features.columns),
            "classes_missing_in_train": missing_in_train,
            "classes_missing_in_test": missing_in_test,
        },
        "points": _points(artifacts),
    }


def _validate(features: pd.DataFrame, timestamps: pd.Series,
              labels: pd.Series, *, split_mode: str) -> ClassificationRefusal | None:
    if labels is None:
        return ClassificationRefusal(
            "no_labels",
            "this source has no label column, so fault classification cannot "
            "be run. No labels were invented: choose the simulated source (or "
            "a file that carries class labels) for supervised results.",
            {"required": "a class label per observation"})
    if features is None or features.shape[1] == 0 or len(features) == 0:
        return ClassificationRefusal(
            "insufficient_features",
            "no time-aligned feature matrix could be built from the selected "
            "metrics, so there is nothing to classify.",
            {"required": "at least one metric series with >= "
                         f"{get_settings().min_points_analysis} aligned points"})
    present = [v for v in labels.tolist() if v is not None]
    if not present:
        return ClassificationRefusal(
            "no_labels", "the label column exists but is empty for this series",
            {"required": "non-null labels"})
    classes = sorted({str(v) for v in present})
    if len(classes) < 2:
        return ClassificationRefusal(
            "single_class",
            f"only one class is present ({classes[0] if classes else 'none'}); "
            "a classifier needs at least two distinct fault classes.",
            {"classes_found": classes})
    counts = pd.Series([str(v) for v in present]).value_counts()
    thin = [c for c, n in counts.items() if n < MIN_ROWS_PER_CLASS]
    if thin:
        return ClassificationRefusal(
            "class_too_thin",
            f"class(es) {thin} have fewer than {MIN_ROWS_PER_CLASS} examples; "
            "scoring them would report noise as accuracy.",
            {"min_rows_per_class": MIN_ROWS_PER_CLASS,
             "class_counts": {str(k): int(v) for k, v in counts.items()}})
    if len(features) != len(labels):
        return ClassificationRefusal(
            "row_mismatch",
            f"{len(features)} feature rows vs {len(labels)} labels: the "
            "alignment is not defensible, so nothing was computed.",
            {"feature_rows": len(features), "label_rows": len(labels)})
    if len(labels) != len(pd.Series(labels).dropna()):
        return ClassificationRefusal(
            "partial_labels",
            f"{int(len(labels) - len(pd.Series(labels).dropna()))} feature rows "
            "have no label; classification is only run on fully labelled rows, "
            "so drop those metrics or supply their classes.",
            {"unlabelled_rows": int(len(labels)
                                    - len(pd.Series(labels).dropna()))})
    if split_mode not in (SPLIT_CHRONOLOGICAL, SPLIT_STRATIFIED):
        raise ValueError(f"unknown split_mode: {split_mode}")
    return None


def _make_split(labels: pd.Series, *, test_frac: float,
                split_mode: str) -> tuple[list[int], list[int]]:
    """Row indices for train/test.

    The chronological branch relies on the caller having passed rows already
    sorted by time (``LabDataset.feature_frame`` returns exactly that), so the
    last ``test_frac`` of the rows are the future. No shuffling happens there.
    """
    n = len(labels)
    if split_mode == SPLIT_CHRONOLOGICAL:
        n_test = max(2, int(round(n * test_frac)))
        n_test = min(n_test, n - 2)
        idx = list(range(n))
        return idx[: n - n_test], idx[n - n_test:]
    from sklearn.model_selection import train_test_split
    train_idx, test_idx = train_test_split(
        list(range(n)), test_size=test_frac, stratify=labels.astype(str),
        random_state=42, shuffle=True)
    return sorted(train_idx), sorted(test_idx)


def _build(name: str, seed: int):
    if name == "logistic_regression":
        from sklearn.linear_model import LogisticRegression
        return LogisticRegression(max_iter=2000, class_weight="balanced",
                                  random_state=seed)
    if name == "random_forest":
        from sklearn.ensemble import RandomForestClassifier
        return RandomForestClassifier(
            n_estimators=200, min_samples_leaf=2, class_weight=
            "balanced_subsample", random_state=seed, n_jobs=1)
    if name == "gradient_boosting":
        from sklearn.ensemble import HistGradientBoostingClassifier
        return HistGradientBoostingClassifier(
            max_iter=200, learning_rate=0.1, random_state=seed)
    raise ValueError(f"unknown classifier: {name}")


def _importances(estimator, columns: list[str]) -> list[dict]:
    """Coefficients or impurity importances - whichever the model exposes."""
    if hasattr(estimator, "feature_importances_"):
        values = list(estimator.feature_importances_)
        kind = "impurity"
    elif hasattr(estimator, "coef_"):
        coef = getattr(estimator, "coef_")
        matrix = [[abs(float(v)) for v in row] for row in coef]
        values = [max((row[i] for row in matrix), default=0.0)
                  for i in range(len(columns))]
        kind = "max |coefficient|"
    else:  # pragma: no cover - both sklearn families are covered above
        return []
    ranked = sorted(zip(columns, values), key=lambda kv: kv[1], reverse=True)
    return [{"feature": f, "importance": round(float(v), 6), "method": kind}
            for f, v in ranked[:10]]


def _points(artifacts: dict) -> list[dict]:
    """Flatten each confusion matrix into (model, true, predicted, count)."""
    out: list[dict] = []
    for name, data in artifacts.get("confusion_matrices", {}).items():
        matrix = data["matrix"]
        for i, true_class in enumerate(data["classes"]):
            for j, pred_class in enumerate(data["classes"]):
                out.append({"model": name, "true": true_class,
                            "predicted": pred_class,
                            "count": int(matrix[i][j])})
    return out


def _best(rows: list[dict]) -> str | None:
    ok = [r for r in rows if r.get("status") == "ok"]
    if not ok:
        return None
    ranked = sorted(ok, key=lambda r: (-r["balanced_accuracy"], -r["macro_f1"],
                                       r["model"]))
    return ranked[0]["model"]


def _num(value) -> float | None:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return None if math.isnan(number) else round(number, 6)


def _warnings(missing_train, missing_test, split_mode, classes,
              counts) -> list[str]:
    notes: list[str] = []
    if split_mode == SPLIT_STRATIFIED:
        notes.append(
            "stratified split chosen: rows from later in the series were part "
            "of training, so these scores are optimistic for time-ordered "
            "telemetry (see config.split_note).")
    if missing_train:
        notes.append("classes absent from the train split: "
                     + ", ".join(missing_train))
    if missing_test:
        notes.append("classes absent from the test split (no evidence to "
                     "score them): " + ", ".join(missing_test))
    ratio = float(counts.max()) / max(1, int(counts.min()))
    if ratio > 5:
        notes.append(
            f"classes are imbalanced (largest/smallest = {ratio:.1f}); only "
            "the imbalance-aware metrics are meaningful here, and the "
            "majority baseline is reported next to every score.")
    if len(classes) > 6:
        notes.append(f"{len(classes)} classes: per-class support is small, so "
                     "read macro averages with care.")
    return notes


def _perfect_split_notes(rows: list[dict]) -> list[str]:
    """Flag a flawless score instead of presenting it as a capability.

    Simulated labels are produced by the very events that move the features, so
    a perfect separation there measures the construction (a link-state label is
    derivable from zero traffic) rather than model skill on a real network. The
    number stays in the table - it is what the protocol produced - but the note
    travels with it.
    """
    perfect = [str(r["model"]) for r in rows
               if r.get("status") == "ok"
               and float(r.get("balanced_accuracy") or 0) >= 1.0]
    if not perfect:
        return []
    return [
        f"{', '.join(perfect)} separated every held-out row correctly. Verify "
        "that the label is not derivable from a feature before reading this as "
        "skill: with simulator-generated labels the fault class and the metric "
        "drop share one cause, so a perfect score is expected and evidences "
        "the construction, not prediction power on a real network."]
