"""Data-source scoping shared by the collector, seed tool and Streamlit pages.

Live and simulated rows share the same tables.  ``metric_samples``,
``collection_runs``, ``connectivity_tests``, ``anomaly_events`` and the other
Phase-2 tables carry an explicit ``data_source`` column.  The structural
tables (``devices``, ``interfaces``, ``links`` and ``incidents``) do **not**,
and this phase is explicitly forbidden from running DDL.

To keep provenance honest without a schema change, structural rows are scoped
deterministically by name:

* simulated structural rows use the reserved ``sim:`` prefix (for example
  ``sim:R1``);
* live structural rows never use that prefix;
* demo mode runs against its own store and is shown behind the demo banner.

This is a documented limitation: a future migration should add a real
``data_source`` column to the structural tables.  Nothing here ever relabels a
simulated row as live (or the reverse).
"""
from __future__ import annotations

from collections.abc import Iterable, Sequence
from typing import Any

LIVE = "live"
SIMULATED = "simulated"
DEMO = "demo"

#: Reserved prefix for structural rows that belong to the simulated source.
SIMULATED_PREFIX = "sim:"

SIMULATED_BANNER = (
    "Simulated lab data - not real telemetry. This source is generated by the "
    "AI Lab simulator and is never mixed with live probe measurements."
)

SOURCE_LABELS = {
    LIVE: "live - real probe measurements",
    SIMULATED: "simulated - AI Lab simulator (NOT real telemetry)",
    DEMO: "demo - synthetic fixtures (NOT real telemetry)",
}


def is_simulated_name(name: str | None) -> bool:
    """True when a structural row name belongs to the simulated source."""
    return bool(name) and str(name).startswith(SIMULATED_PREFIX)


def tag_simulated(name: str) -> str:
    """Return the reserved simulated name for a simulator device label."""
    text = str(name)
    return text if is_simulated_name(text) else SIMULATED_PREFIX + text


def strip_simulated(name: str) -> str:
    """Return the simulator's own label for a stored simulated device name."""
    text = str(name)
    return text[len(SIMULATED_PREFIX):] if is_simulated_name(text) else text


def structural_matches(name: str | None, source: str) -> bool:
    """Deterministic source test for a structural row name.

    Demo mode is not filtered here: it is isolated by its own database/store
    and always carries the demo banner.
    """
    if source == SIMULATED:
        return is_simulated_name(name)
    if source == LIVE:
        return not is_simulated_name(name)
    return True


def filter_devices(devices: Iterable[Any], source: str) -> list[Any]:
    return [d for d in devices if structural_matches(getattr(d, "name", None),
                                                      source)]


def filter_links(links: Iterable[Any], source: str) -> list[Any]:
    return [link for link in links
            if structural_matches(getattr(link, "device_a", None), source)
            and structural_matches(getattr(link, "device_b", None), source)]


def filter_incidents(incidents: Iterable[Any], source: str) -> list[Any]:
    return [inc for inc in incidents
            if structural_matches(getattr(inc, "device_name", None), source)]


def filter_names(names: Iterable[str], source: str) -> list[str]:
    return [name for name in names if structural_matches(name, source)]


def available_sources(session) -> list[str]:
    """Return the sources that actually have rows, ordered for the UI.

    The default should always be a source that has data. When only simulated rows
    exist we prefer simulated first; when live rows exist, live stays first.
    When neither source has data the UI still presents the live source as the
    default entry point for collection, without inventing a fake simulated graph.
    """
    found: set[str] = set()
    try:
        from database import repository
        for (_device, _metric, _unit, source) in repository.get_available_metrics(session):
            if source:
                found.add(str(source))
    except Exception:  # noqa: BLE001 - a page must render even if the DB is down
        found = set()
    found.discard(DEMO)

    if not found:
        return [LIVE]

    others = sorted(found - {LIVE, SIMULATED})
    if LIVE in found and SIMULATED in found:
        result = [LIVE, SIMULATED]
    elif SIMULATED in found:
        result = [SIMULATED, LIVE]
    else:
        result = [LIVE]
    result.extend(others)
    return result


def default_source(sources: Sequence[str], demo_mode: bool = False) -> str:
    """Live when live rows exist; otherwise the first offered source."""
    if demo_mode:
        return DEMO
    return sources[0] if sources else LIVE


def has_rows(session, source: str) -> bool:
    """True when the source has at least one stored non-null measurement."""
    from database import repository
    return any(str(src) == source
               for (_device, _metric, _unit, src)
               in repository.get_available_metrics(session))
